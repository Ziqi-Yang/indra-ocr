"""Generate crates/indra-ocr/src/unitab.rs: Python's str predicates and the
unicodedata properties the pipeline reads, as code point range tables, so the
Rust port classifies every character exactly as Python does.

    uv run --no-project python tools/gen_unicode_tables.py > crates/indra-ocr/src/unitab.rs
"""

import sys
import unicodedata


def ranges(pred):
    out, start = [], None
    for cp in range(0x110000):
        c = chr(cp)
        ok = pred(c)
        if ok and start is None:
            start = cp
        elif not ok and start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def bad(c):
    cat = unicodedata.category(c)
    return c == "�" or cat in ("Co", "Cs", "Cn") or (cat == "Cc" and c != "\t")


TABLES = {
    "ALPHA": str.isalpha,
    "DIGIT": str.isdigit,
    "DECIMAL": str.isdecimal,
    "UPPER": str.isupper,
    "LOWER": str.islower,
    "SPACE": str.isspace,
    "BAD": bad,
    "BIDI_RTL": lambda c: unicodedata.bidirectional(c) in ("R", "AL"),
    "BIDI_LTR": lambda c: unicodedata.bidirectional(c) == "L",
}

print(f"// Generated by tools/gen_unicode_tables.py (Python {sys.version.split()[0]}, "
      f"Unicode {unicodedata.unidata_version}). Do not edit.")
print("#![allow(clippy::unreadable_literal)]")
for name, pred in TABLES.items():
    rs = ranges(pred)
    print(f"pub static {name}: [(u32, u32); {len(rs)}] = [")
    line = "   "
    for a, b in rs:
        item = f" (0x{a:X}, 0x{b:X}),"
        if len(line) + len(item) > 100:
            print(line)
            line = "   "
        line += item
    print(line)
    print("];")
